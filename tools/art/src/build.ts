/**
 * `pnpm art`: regenerate the sprite atlas (apps/web/public/atlas/atlas.png + atlas.json).
 * `--preview <dir>` also writes upscaled contact sheets for screenshot review.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allSprites } from './sprites.ts';
import { pack } from './atlas.ts';
import { rgba, PALETTE } from './palette.ts';
import { encodePng } from './png.ts';
import { upscale } from './scaled.ts';
import { composeScene } from './scene.ts';
import { uiSprites } from './ui.ts';
import { ICONS } from './icons.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const OUT = resolve(ROOT, 'apps/web/public/atlas');

export function buildAtlas() {
  const atlas = pack(allSprites());
  const png = encodePng(atlas.image, rgba());
  const json = {
    _doc: 'Generated by tools/art (pnpm art). Original art, CC BY 4.0. Do not edit by hand.',
    size: [atlas.image.width, atlas.image.height],
    palette: PALETTE.map(([n, hex]) => [n, hex]),
    frames: atlas.frames,
  };
  return { atlas, png, json: JSON.stringify(json, null, 1) + '\n' };
}

