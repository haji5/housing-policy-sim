export const FONT_CHARS = Object.keys(G).join('');

/** One sprite per glyph, white on transparent (recoloured at draw time by the web renderer). */
export function glyphs(color: number = C.white): Record<string, Sprite> {
  const out: Record<string, Sprite> = {};
  for (const [ch, def] of Object.entries(G)) {
    const rows = def.split('|');
    if (rows.length !== 7 || rows.some((r) => r.length !== 5))
      throw new Error(`glyph ${ch} must be 5x7`);
    const s = new Sprite(5, 7);
    rows.forEach((r, y) => {
      for (let x = 0; x < 5; x++) if (r[x] === '#') s.set(x, y, color);
    });
    out[`font_${ch.charCodeAt(0)}`] = s;
  }
  return out;
}
